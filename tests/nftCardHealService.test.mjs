test('deriveMvcFirstInputAddressFromRawTx pins the mainnet minter of MetaBot Avatar #7898', () => {
  if (!healService) return; // dist-electron not built in this checkout
  assert.equal(
    healService.deriveMvcFirstInputAddressFromRawTx(META_TX_7898_HEX),
    '132n3Z5UymSCQAaTcmnCGKeHVxsVgkBuJS',
  );
});

test('deriveMvcFirstInputAddressFromRawTx rejects malformed txs and pubkey-less inputs', () => {
  if (!healService) return;
  // Not hex at all / too short.
  assert.equal(healService.deriveMvcFirstInputAddressFromRawTx('zzzz'), null);
  assert.equal(healService.deriveMvcFirstInputAddressFromRawTx(''), null);
  // Well-formed tx whose only input carries an EMPTY scriptSig (no pubkey).
  // version=1, in-count=1, prevout=0x00*36, scriptLen=0, sequence, out-count=0.
  const noPubkey = `0100000001${'00'.repeat(36)}00000000ffffffff00000000`;
  assert.equal(healService.deriveMvcFirstInputAddressFromRawTx(noPubkey), null);
});

test('healNftCard answers empty for unknown formats instead of touching the network', async () => {
  if (!healService) return;
  assert.deepEqual(await healService.healNftCard({ format: 'nope' }), {});
  assert.deepEqual(await healService.healNftCard(undefined), {});
});

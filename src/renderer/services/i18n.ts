/**
 * Map an OS/Chromium locale to the app language.
 * Only Simplified Chinese locales use zh; Traditional Chinese and every other
 * locale fall back to English.
 *
 * Keep this logic in sync with src/main/libs/appLanguage.ts.
 */
export function inferLanguageFromLocale(systemLocale: string): LanguageType {
  const normalized = String(systemLocale || '').trim().replace(/_/g, '-').toLowerCase();
  if (!normalized) {
    return 'en';
  }

  const tags = normalized.split('-').filter(Boolean);
  if (tags[0] !== 'zh') {
    return 'en';
  }

  if (tags.includes('hant') || tags[1] === 'tw' || tags[1] === 'hk' || tags[1] === 'mo') {
    return 'en';
  }

  return 'zh';
}

class I18nService {
  private currentLanguage: LanguageType = 'en';
  private listeners = new Set<() => void>();
  
  constructor() {
    // Default to English until initialize() reads the saved or OS locale.
    // First paint (loading screen) must not flash Chinese for non-zh users.
    this.currentLanguage = 'en';
  }
  
  // 初始化语言设置
  async initialize(): Promise<void> {
    try {
      const config = configService.getConfig();

      // 检查是否已经初始化过语言设置
      const languageInitialized = config.language_initialized;

      if (languageInitialized !== true) {
        // 可能是首次启动或旧版本用户升级
        // 为了保护旧用户的语言设置,检查是否有非默认的语言配置
        const hasCustomLanguage = config.language && config.language !== 'zh';

        if (hasCustomLanguage) {
          // 旧用户已手动设置过语言(非默认值),保留他们的设置
          console.log(`[i18n] Legacy user detected with custom language: ${config.language}`);
          this.currentLanguage = config.language;
          configService.updateConfig({
            ...config,
            language_initialized: true
          });
        } else {
          // 新用户或使用默认中文的旧用户:检测系统语言
          try {
            const systemLocale = await window.electron.appInfo.getSystemLocale();
            const defaultLanguage = inferLanguageFromLocale(systemLocale);

            console.log(`[i18n] First run detected. System locale: ${systemLocale}, default language: ${defaultLanguage}`);

            this.currentLanguage = defaultLanguage;

            // 保存语言配置和初始化标记
            configService.updateConfig({
              ...config,
              language: defaultLanguage,
              language_initialized: true
            });
          } catch (error) {
            console.error('Failed to get system locale:', error);
            // 如果获取系统语言失败,默认使用英文
            this.currentLanguage = 'en';
            configService.updateConfig({
              ...config,
              language: 'en',
              language_initialized: true
            });
          }
        }
      } else {
        // 非首次启动:使用已保存的语言配置
        if (config.language && (config.language === 'zh' || config.language === 'en')) {
          this.currentLanguage = config.language;
        } else {
          // 如果配置无效,fallback 到英文
          this.currentLanguage = 'en';
          configService.updateConfig({
            ...config,
            language: 'en'
          });
        }
      }
    } catch (error) {
      console.error('Failed to initialize language:', error);
      this.currentLanguage = 'en';
    }

    this.listeners.forEach((listener) => listener());
  }
  
  // 设置语言
  setLanguage(language: LanguageType, options: { persist?: boolean } = {}): void {
    const { persist = true } = options;
    const hasChanged = this.currentLanguage !== language;
    this.currentLanguage = language;

    if (hasChanged) {
      this.listeners.forEach((listener) => listener());
    }

    if (!persist) {
      return;
    }

    // 更新配置
    try {
      const config = configService.getConfig();
      configService.updateConfig({
        ...config,
        language
      });
    } catch (error) {
      console.error('Failed to save language setting:', error);
    }
  }
  
  // 获取当前语言
  getLanguage(): LanguageType {
    return this.currentLanguage;
  }
  
  // 获取翻译文本
  t(key: string): string {
    const translation = translations[this.currentLanguage][key];
    if (!translation) {
      console.warn(`Translation missing for key: ${key} in language: ${this.currentLanguage}`);
      if (this.currentLanguage === 'en') {
        // Never fall back to Chinese in the English UI.
        return key;
      }
      return translations.en[key] || key;
    }
    return translation;
  }

  subscribe(listener: () => void): () => void {
    this.listeners.add(listener);
    return () => {
      this.listeners.delete(listener);
    };
  }
}

export const i18nService = new I18nService(); 
